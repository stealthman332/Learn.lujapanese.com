export const KANJI = (() => {
  const seen = new Set(), out = [];
  for (const r of KANJI_RAW) {
    if (seen.has(r[0])) continue; seen.add(r[0]);
    out.push({
      ch: r[0], mean: r[1], on: r[2], kun: r[3], strokes: r[4], jlpt: r[5],
      words: (r[6] || "").split(";").filter(Boolean).map(w => {
        const [t, r2, g] = w.split("|"); return { w: t.trim(), r: (r2 || "").trim(), g: (g || "").trim() };
      })
    });
  }
  return out;
})();
